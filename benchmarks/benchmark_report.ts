import { formatNs, getMetrics, readOrRunBenchmarks } from "./bench_results.ts";

function option(name: string): string | undefined {
  const index = Deno.args.indexOf(name);
  return index >= 0 ? Deno.args[index + 1] : undefined;
}

async function revision(): Promise<string> {
  if (Deno.env.get("GITHUB_SHA")) {
    return Deno.env.get("GITHUB_SHA")!.slice(0, 12);
  }
  try {
    const result = await new Deno.Command("git", {
      args: ["rev-parse", "--short=12", "HEAD"],
      stdout: "piped",
      stderr: "null",
    }).output();
    if (result.success) {
      return new TextDecoder().decode(result.stdout).trim();
    }
  } catch {
    // Report remains useful outside a Git checkout.
  }
  return "unknown";
}

async function workingTree(): Promise<string> {
  try {
    const result = await new Deno.Command("git", {
      args: ["status", "--porcelain"],
      stdout: "piped",
      stderr: "null",
    }).output();
    if (result.success) {
      return new TextDecoder().decode(result.stdout).trim()
        ? "dirty (includes uncommitted changes)"
        : "clean";
    }
  } catch {
    // Report remains useful outside a Git checkout.
  }
  return "unknown";
}

const inputPath = option("--input");
const outputPath = option("--output") ?? "docs/benchmarks.md";
const results = await readOrRunBenchmarks(inputPath);
const rows = (results.benches ?? []).flatMap((bench) => {
  const metrics = getMetrics(bench);
  return bench.name && metrics
    ? [{
      name: bench.name,
      group: bench.group ?? "other",
      ...metrics,
    }]
    : [];
});
const buildRows = rows.filter((row) => row.name.startsWith("build ("));
const microRows = rows.filter((row) => !row.name.startsWith("build ("));
const memory = Deno.systemMemoryInfo();
const generatedAt = new Date().toISOString();

function table(
  entries: typeof rows,
): string {
  return [
    "| Scenario | Samples | Min | Average | p75 | p99 |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
    ...entries.map((row) =>
      `| ${row.name} | ${row.n} | ${formatNs(row.min)} | ${
        formatNs(row.avg)
      } | ${formatNs(row.p75)} | ${formatNs(row.p99)} |`
    ),
  ].join("\n");
}

const report = `# Steno benchmark report

This report is generated by \`deno task bench:report\`. Results are evidence
from one machine, not universal guarantees; compare runs made on equivalent
hardware and runtime versions.

## Environment

- Generated: ${generatedAt}
- Revision: ${await revision()}
- Working tree: ${await workingTree()}
- Runtime: ${results.runtime ?? `Deno/${Deno.version.deno}`}
- OS: ${Deno.build.os} ${Deno.osRelease()}
- Architecture: ${Deno.build.arch}
- Logical CPUs: ${navigator.hardwareConcurrency}
- System memory: ${(memory.total / 1024 ** 3).toFixed(1)} GiB

## Build scenarios

${table(buildRows)}

Cold scenarios delete output and persistent cache before every measured build.
Warm unchanged uses an initialized 1,000-page site. Atomic incremental changes
one page while retaining transactional staging and promotion. Fixture creation
is outside the explicit benchmark timer.

## Parser and template microbenchmarks

${table(microRows)}

## Reproduce

\`\`\`sh
deno task bench:report
deno task bench:check
\`\`\`

Run on an otherwise idle machine. The performance gate evaluates averages
against committed budgets; this report additionally publishes sample count,
minimum, p75, and p99 latency.
`;

await Deno.writeTextFile(outputPath, report);
console.log(`Wrote benchmark report to ${outputPath}`);
